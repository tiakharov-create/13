def decode(units, start=0, end=None):
    """yield (pc, opcode, units_of_instr)"""
    if end is None: end=len(units)
    pc=start
    while pc < end:
        u=units[pc]; op=u&0xff
        n=SIZE[op]
        if pc+n>end: break
        yield pc, op, units[pc:pc+n]
        pc+=n
